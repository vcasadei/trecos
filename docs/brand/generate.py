#!/usr/bin/env python3
"""Draws the Trecos logo (a lidded cardboard box with a handwritten label).

Writes the SVGs in this folder and the launcher icon vector drawables in
app/src/main/res. Run it from anywhere after changing the drawing:

    python3 docs/brand/generate.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent.parent / "app" / "src" / "main" / "res"

INK, OUTLINE, LABEL, VIOLET = "#23201C", "#4A2E17", "#FFFFFF", "#651FFF"
BODY_FRONT, BODY_SIDE = "#C98A4B", "#A86A33"
LID_TOP, LID_FRONT, LID_SIDE = "#E8B677", "#D59A58", "#B47639"

# Handwritten strokes, drawn with a 7-unit round pen on a baseline at y=70.
T = ["M10,10 C10,30 8,55 12,68 C14,74 20,74 26,70", "M0,30 L24,28"]
T_BOUNDS = (0, 10, 26, 74)
WORD = T + [
    "M34,36 C35,50 35,60 34,70", "M35,48 C40,38 48,34 56,38",
    "M64,56 L90,52 C92,40 80,34 72,38 C62,44 62,64 72,70 C80,74 88,72 94,66",
    "M124,42 C116,34 102,38 100,52 C98,66 108,74 118,72 C122,71 125,69 127,66",
    "M152,38 C140,38 134,50 136,60 C138,70 146,74 154,72 C164,69 168,58 165,48 C163,40 158,37 152,38 Z",
    "M196,40 C190,35 178,36 178,44 C178,52 196,52 196,62 C196,72 182,74 174,68",
]
WORD_BOUNDS = (0, 10, 196, 74)
PEN = 7


def box(scale, ox, oy, outline, label, ink=None):
    """The box in a 62x50 frame, scaled and moved to (ox, oy).

    Returns (faces, label) where faces are (fill, points, alpha, stroked) and
    label holds the tilted label with its ink strokes.
    """
    def pts(*p):
        return [(ox + x * scale, oy + y * scale) for x, y in p]
    faces = [
        (BODY_SIDE, pts((46, 16), (60, 8), (60, 42), (46, 50)), 1.0, True),
        (BODY_FRONT, pts((2, 16), (46, 16), (46, 50), (2, 50)), 1.0, True),
        (OUTLINE, pts((2, 17), (46, 17), (46, 20), (2, 20)), 0.25, False),  # lid shadow
        (OUTLINE, pts((51, 24.5), (56, 21.6), (56, 24.6), (51, 27.5)), 1.0, True),  # handle
        (LID_SIDE, pts((48, 8), (62, 0), (62, 9), (48, 17)), 1.0, True),
        (LID_TOP, pts((0, 8), (14, 0), (62, 0), (48, 8)), 1.0, True),
        (LID_FRONT, pts((0, 8), (48, 8), (48, 17), (0, 17)), 1.0, True),
    ]
    lx, ly, lw, lh = label
    tag = {
        "x": ox + lx * scale, "y": oy + ly * scale, "w": lw * scale, "h": lh * scale,
        "r": 1.6 * scale, "cx": ox + (lx + lw / 2) * scale, "cy": oy + (ly + lh / 2) * scale,
        "shadow": (outline * 0.6, outline * 0.9), "outline": outline, "ink": None,
    }
    if ink:
        paths, (x0, y0, x1, y1), k = ink
        s = k * scale
        tag["ink"] = (paths, tag["cx"] - (x0 + x1) / 2 * s, tag["cy"] - (y0 + y1) / 2 * s, s)
    return faces, tag


def n(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def poly(points):
    return "M" + " L".join(f"{n(x)},{n(y)}" for x, y in points) + " Z"


def rrect(x, y, w, h, r):
    return (f"M{n(x + r)},{n(y)} H{n(x + w - r)} A{n(r)},{n(r)} 0 0 1 {n(x + w)},{n(y + r)} "
            f"V{n(y + h - r)} A{n(r)},{n(r)} 0 0 1 {n(x + w - r)},{n(y + h)} H{n(x + r)} "
            f"A{n(r)},{n(r)} 0 0 1 {n(x)},{n(y + h - r)} V{n(y + r)} A{n(r)},{n(r)} 0 0 1 {n(x + r)},{n(y)} Z")


def svg(size, drawing, background=None):
    faces, tag = drawing
    w, h = size
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">']
    if background:
        out.append(f'<rect width="{w}" height="{h}" fill="{background}"/>')
    for fill, p, alpha, stroked in faces:
        line = f' stroke="{OUTLINE}" stroke-width="{n(tag["outline"])}" stroke-linejoin="round"' if stroked else ""
        op = f' opacity="{alpha}"' if alpha < 1 else ""
        out.append(f'<path d="{poly(p)}" fill="{fill}"{op}{line}/>')
    dx, dy = tag["shadow"]
    out.append(f'<g transform="rotate(-3 {n(tag["cx"])} {n(tag["cy"])})">')
    out.append(f'<path d="{rrect(tag["x"] + dx, tag["y"] + dy, tag["w"], tag["h"], tag["r"])}" fill="{OUTLINE}" opacity="0.35"/>')
    out.append(f'<path d="{rrect(tag["x"], tag["y"], tag["w"], tag["h"], tag["r"])}" fill="{LABEL}" '
               f'stroke="{OUTLINE}" stroke-width="{n(tag["outline"])}"/>')
    if tag["ink"]:
        paths, tx, ty, s = tag["ink"]
        out.append(f'<g transform="translate({n(tx)} {n(ty)}) scale({s:.4f})" fill="none" stroke="{INK}" '
                   f'stroke-width="{PEN}" stroke-linecap="round" stroke-linejoin="round">')
        out += [f'<path d="{d}"/>' for d in paths]
        out.append("</g>")
    out += ["</g>", "</svg>", ""]
    return "\n".join(out)


def argb(color, alpha=1.0):
    return f"#{round(alpha * 255):02X}{color[1:]}"


def vector(drawing, mono=False):
    """A 108dp adaptive-icon layer. mono draws the outline only, for themed icons."""
    faces, tag = drawing
    sw = n(tag["outline"])
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by docs/brand/generate.py; edit the script, not this file. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp"', '    android:height="108dp"',
           '    android:viewportWidth="108"', '    android:viewportHeight="108">']

    def path(d, fill=None, stroke=None, width=None, cap=False, alpha=1.0, indent="    "):
        attrs = [f'android:pathData="{d}"']
        if fill:
            attrs.append(f'android:fillColor="{argb(fill, alpha)}"')
        if stroke:
            attrs += [f'android:strokeColor="{argb(stroke)}"', f'android:strokeWidth="{width}"',
                      'android:strokeLineJoin="round"']
            if cap:
                attrs.append('android:strokeLineCap="round"')
        sep = "\n" + indent + "    "
        out.append(f"{indent}<path{sep}" + sep.join(attrs) + " />")

    for fill, p, alpha, stroked in faces:
        if mono:
            if alpha == 1.0:
                path(poly(p), fill="#000000" if fill == OUTLINE else None, stroke="#000000", width=sw)
        else:
            path(poly(p), fill=fill, alpha=alpha, stroke=OUTLINE if stroked else None, width=sw)
    out.append(f'    <group android:rotation="-3" android:pivotX="{n(tag["cx"])}" android:pivotY="{n(tag["cy"])}">')
    dx, dy = tag["shadow"]
    label = rrect(tag["x"], tag["y"], tag["w"], tag["h"], tag["r"])
    if mono:
        path(label, stroke="#000000", width=sw, indent="        ")
    else:
        path(rrect(tag["x"] + dx, tag["y"] + dy, tag["w"], tag["h"], tag["r"]), fill=OUTLINE, alpha=0.35, indent="        ")
        path(label, fill=LABEL, stroke=OUTLINE, width=sw, indent="        ")
    if tag["ink"]:
        paths, tx, ty, s = tag["ink"]
        out.append(f'        <group android:translateX="{n(tx)}" android:translateY="{n(ty)}" '
                   f'android:scaleX="{s:.4f}" android:scaleY="{s:.4f}">')
        for d in paths:
            path(d, stroke="#000000" if mono else INK, width=PEN, cap=True, indent="            ")
        out.append("        </group>")
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


# The launcher shows only the middle of the 108dp layer: the 0.76 icon scale keeps
# every corner of the box inside the 66dp safe circle.
ICON = box(0.76, 30.44, 35, 1.2, (7, 25, 34, 21), (T, T_BOUNDS, 0.26))
LOGO = box(4.6, 28, 25, 4, (4, 25, 40, 20), (WORD, WORD_BOUNDS, 0.177))

if __name__ == "__main__":
    (HERE / "trecos-icon.svg").write_text(svg((108, 108), ICON, VIOLET))
    (HERE / "trecos-logo.svg").write_text(svg((340, 280), LOGO))
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector(ICON))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(vector(ICON, mono=True))
